"""Editing one action slot — the single write capability of Phase 2 (SPEC §5).

Everything a write has to get right lives here: the URL for a Shelly target is
generated by the server and never taken from the client (§4), one write at a
time per device, the device is re-read and compared field by field before the
write is called a success (§5.3), and every attempt lands in `audit_log`.
"""

from __future__ import annotations

import asyncio
import hashlib
import json
import logging
import time
import uuid
from dataclasses import dataclass, field
from typing import Any

import httpx

from .adapters import gen1, gen2
from .config import Settings
from .db import Database
from .discovery import auth_for, load_credentials, now_iso
from .generator import UnsupportedCommand, build_url
from .graph import load_device_refs, rebuild_edges
from .models import BuiltUrlSpec, HaWebhookSpec, RawExternalSpec, SlotUpdate, UrlTestResult
from .resolver import resolve

log = logging.getLogger(__name__)

DEMO_TEST_DELAY_S = 0.15
BODY_SNIPPET_CHARS = 200

_locks: dict[str, asyncio.Lock] = {}


def device_lock(device_id: str) -> asyncio.Lock:
    """One in-flight write per device (SPEC §5.3)."""
    return _locks.setdefault(device_id, asyncio.Lock())


class SlotWriteError(Exception):
    """A write that must not be reported as a success."""

    def __init__(self, status: int, code: str, detail: str, extra: dict[str, Any] | None = None):
        super().__init__(detail)
        self.status = status
        self.code = code
        self.detail = detail
        self.extra = extra or {}


@dataclass
class SlotState:
    enabled: bool
    urls: list[str] = field(default_factory=list)

    @property
    def revision(self) -> str:
        payload = json.dumps([self.enabled, self.urls], separators=(",", ":"))
        return hashlib.sha1(payload.encode()).hexdigest()[:12]


def revision_of(enabled: bool, urls: list[str]) -> str:
    return SlotState(enabled, urls).revision


async def stored_state(db: Database, slot_id: str) -> SlotState:
    row = await db.fetchone("SELECT enabled FROM action_slots WHERE id = ?", (slot_id,))
    if row is None:
        raise SlotWriteError(404, "not_found", f"no slot {slot_id}")
    urls = await db.fetchall(
        "SELECT raw_url FROM action_urls WHERE slot_id = ? ORDER BY position", (slot_id,)
    )
    return SlotState(bool(row["enabled"]), [url["raw_url"] for url in urls])


async def ha_base_url(db: Database) -> str | None:
    row = await db.fetchone("SELECT value FROM app_settings WHERE key = 'ha_base_url'")
    return row["value"] if row is not None else None


async def resolve_specs(
    db: Database, specs: list[Any], already_stored: list[str] | None = None
) -> list[str]:
    """Turn the editor's URL specs into concrete URLs, refusing what §5.1 forbids."""
    refs = await load_device_refs(db)
    stored = set(already_stored or ())
    urls: list[str] = []

    for spec in specs:
        if isinstance(spec, BuiltUrlSpec):
            device = await db.fetchone(
                "SELECT ip, gen FROM devices WHERE id = ?", (spec.target_device_id,)
            )
            if device is None:
                raise SlotWriteError(404, "not_found", f"no device {spec.target_device_id}")
            channel = await db.fetchone(
                "SELECT kind, idx FROM channels WHERE id = ? AND device_id = ?",
                (spec.channel_id, spec.target_device_id),
            )
            if channel is None:
                raise SlotWriteError(
                    404, "not_found", f"no channel {spec.channel_id} on that device"
                )
            try:
                built = build_url(
                    device["ip"],
                    device["gen"],
                    channel["kind"],
                    channel["idx"],
                    spec.command,
                    spec.params,
                )
            except UnsupportedCommand as exc:
                raise SlotWriteError(422, "unsupported_command", str(exc)) from exc
            urls.append(built.url)

        elif isinstance(spec, HaWebhookSpec):
            base = await ha_base_url(db)
            if not base:
                raise SlotWriteError(
                    422, "ha_base_url_unset", "set the Home Assistant base URL in settings first"
                )
            webhook_id = spec.webhook_id.strip().strip("/")
            if not webhook_id:
                raise SlotWriteError(422, "invalid_webhook", "a webhook id is required")
            urls.append(f"{base}/api/webhook/{webhook_id}")

        elif isinstance(spec, RawExternalSpec):
            raw = spec.url.strip()
            if not raw:
                raise SlotWriteError(422, "invalid_url", "a URL is required")
            parsed = resolve(raw, refs)
            if parsed.target_type == "device" and raw not in stored:
                # §4/§5.1: the app builds every Shelly-target URL, and the rule
                # is enforced here rather than only in the form. A URL already on
                # this slot may be kept verbatim — the editor cannot rebuild one
                # the resolver does not understand, and keeping it introduces
                # nothing the device does not already have.
                raise SlotWriteError(
                    422,
                    "raw_url_targets_a_device",
                    "that URL points at an inventoried Shelly; build it with the wizard instead",
                    {"target_device_id": parsed.target_device_id},
                )
            urls.append(raw)

        else:  # pragma: no cover - the discriminated union covers every kind
            raise SlotWriteError(422, "invalid_spec", f"unknown URL spec {spec!r}")

    return urls


async def record_attempt(
    db: Database, device_id: str, action: str, payload: dict[str, Any], result: str
) -> None:
    await db.execute(
        "INSERT INTO audit_log (id, ts, device_id, action, payload, result) VALUES (?, ?, ?, ?, ?, ?)",
        (str(uuid.uuid4()), now_iso(), device_id, action, json.dumps(payload), result),
    )


async def _client(settings: Settings) -> httpx.AsyncClient:
    return httpx.AsyncClient(timeout=httpx.Timeout(settings.http_timeout_s), follow_redirects=True)


async def _write_to_device(
    db: Database,
    settings: Settings,
    device: Any,
    slot: Any,
    wanted: SlotState,
    delete_hook: bool,
) -> tuple[SlotState, str | None]:
    """Write, then re-read. Returns the device's state and any new slot id."""
    credentials = (await load_credentials(db)).get(device["id"])
    auth = auth_for(device["gen"], *credentials) if credentials else None

    async with await _client(settings) as client:
        if device["gen"] >= 2:
            hook_id = gen2.hook_id_of(slot["id"])

            if delete_hook and hook_id is not None:
                await gen2.delete_hook(client, device["ip"], hook_id, auth)
                if await gen2.read_hook(client, device["ip"], hook_id, auth) is not None:
                    raise SlotWriteError(
                        502, "verify_failed", "the device still reports the webhook after deleting it"
                    )
                return SlotState(False, []), None

            created: str | None = None
            if hook_id is None:
                hook_id = await gen2.create_hook(
                    client,
                    device["ip"],
                    slot["source_idx"],
                    slot["native_key"],
                    wanted.enabled,
                    wanted.urls,
                    slot["name"],
                    auth,
                )
                created = f"{device['id']}:hook:{hook_id}"
            else:
                await gen2.write_hook(
                    client, device["ip"], hook_id, wanted.enabled, wanted.urls, auth
                )
            read = await gen2.read_hook(client, device["ip"], hook_id, auth)
            if read is None:
                raise SlotWriteError(
                    502, "verify_failed", "the device no longer reports this webhook"
                )
            return SlotState(read[0], read[1]), created

        await gen1.write_slot(
            client,
            device["ip"],
            slot["native_key"],
            slot["source_idx"],
            wanted.enabled,
            wanted.urls,
            auth,
        )
        enabled, urls = await gen1.read_slot(
            client, device["ip"], slot["native_key"], slot["source_idx"], auth
        )
        return SlotState(enabled, urls), None


async def apply_slot_update(
    db: Database, settings: Settings, slot_id: str, update: SlotUpdate
) -> str:
    """Write a slot to its device, verify it, record it locally; return its id.

    The id changes when a Gen2/3 webhook is created for a slot that had none:
    the device names the hook, and the slot moves from `:newhook:` to `:hook:`.
    """
    slot = await db.fetchone(
        """
        SELECT s.*, d.ip AS ip, d.gen AS gen, d.online AS online, d.name AS device_name
        FROM action_slots s JOIN devices d ON d.id = s.device_id WHERE s.id = ?
        """,
        (slot_id,),
    )
    if slot is None:
        raise SlotWriteError(404, "not_found", f"no slot {slot_id}")

    current = await stored_state(db, slot_id)
    if update.expect_revision and update.expect_revision != current.revision:
        raise SlotWriteError(
            409,
            "stale_slot",
            "device changed — reload the slot before saving",
            {"revision": current.revision},
        )

    urls = await resolve_specs(db, list(update.urls), current.urls)
    wanted = SlotState(update.enabled, urls)
    is_new_hook = slot["gen"] >= 2 and gen2.hook_id_of(slot["id"]) is None
    if is_new_hook and not urls:
        raise SlotWriteError(
            422,
            "nothing_to_create",
            "add a URL first — this device has no webhook for that event yet",
        )
    delete_hook = bool(slot["gen"] >= 2 and not urls and not is_new_hook)
    if delete_hook and not update.confirm_delete:
        raise SlotWriteError(
            409,
            "confirm_delete",
            "removing the last URL deletes this webhook from the device; confirm to proceed",
        )

    device = {"id": slot["device_id"], "ip": slot["ip"], "gen": slot["gen"]}
    payload = {"enabled": wanted.enabled, "urls": wanted.urls, "delete": delete_hook}
    action = "webhook_delete" if delete_hook else "slot_update"

    async with device_lock(slot["device_id"]):
        if settings.demo_mode:
            # §5.5: writes mutate the fixture database only.
            created = await _demo_hook_id(db, slot) if is_new_hook else None
            await _store_locally(db, slot, wanted, delete_hook, created)
            await record_attempt(db, device["id"], action, payload, "simulated")
            return created or slot["id"]

        if not slot["online"]:
            await record_attempt(db, device["id"], action, payload, "failed:device_offline")
            raise SlotWriteError(
                409,
                "device_offline",
                f"{slot['device_name'] or device['id']} is offline; it cannot be edited now",
            )

        try:
            written, created = await _write_to_device(
                db, settings, device, slot, wanted, delete_hook
            )
        except SlotWriteError as exc:
            await record_attempt(db, device["id"], action, payload, f"failed:{exc.code}")
            raise
        except Exception as exc:
            await record_attempt(db, device["id"], action, payload, f"failed:{type(exc).__name__}")
            raise SlotWriteError(502, "write_failed", f"the device refused the write: {exc}") from exc

        if not delete_hook and (written.enabled != wanted.enabled or written.urls != wanted.urls):
            await record_attempt(db, device["id"], action, payload, "failed:verify_mismatch")
            raise SlotWriteError(
                502,
                "verify_mismatch",
                "the device did not store what was sent",
                {
                    "sent": {"enabled": wanted.enabled, "urls": wanted.urls},
                    "stored": {"enabled": written.enabled, "urls": written.urls},
                },
            )

        await _store_locally(db, slot, written, delete_hook, created)
        await record_attempt(db, device["id"], action, payload, "verified")
        return created or slot["id"]


async def _demo_hook_id(db: Database, slot: Any) -> str:
    """A plausible hook id for demo mode, where no device hands one out."""
    rows = await db.fetchall(
        "SELECT id FROM action_slots WHERE device_id = ?", (slot["device_id"],)
    )
    used = [hook for hook in (gen2.hook_id_of(row["id"]) for row in rows) if hook is not None]
    return f"{slot['device_id']}:hook:{(max(used) + 1) if used else 0}"


async def _store_locally(
    db: Database, slot: Any, state: SlotState, deleted: bool, new_slot_id: str | None = None
) -> None:
    """Mirror the device's new state, then rebuild the edges it feeds."""
    slot_id = slot["id"]
    if deleted:
        await db.execute("DELETE FROM action_slots WHERE id = ?", (slot_id,))
    else:
        await db.execute("DELETE FROM action_urls WHERE slot_id = ?", (slot_id,))
        if new_slot_id and new_slot_id != slot_id:
            # The device named the webhook it just created; follow it.
            await db.execute(
                "UPDATE action_slots SET id = ? WHERE id = ?", (new_slot_id, slot_id)
            )
            slot_id = new_slot_id
        await db.execute(
            "UPDATE action_slots SET enabled = ? WHERE id = ?", (int(state.enabled), slot_id)
        )
        await db.executemany(
            "INSERT INTO action_urls (id, slot_id, position, raw_url) VALUES (?, ?, ?, ?)",
            [
                (f"{slot_id}#{position}", slot_id, position, url)
                for position, url in enumerate(state.urls)
            ],
        )
    await rebuild_edges(db)


async def test_url(settings: Settings, url: str) -> UrlTestResult:
    """Fire a URL once, server-side, and report what came back (SPEC §5.1)."""
    if settings.demo_mode:
        await asyncio.sleep(DEMO_TEST_DELAY_S)
        return UrlTestResult(
            status_code=200,
            elapsed_ms=int(DEMO_TEST_DELAY_S * 1000),
            body_snippet="demo mode: nothing was sent",
            simulated=True,
        )

    started = time.monotonic()
    try:
        async with await _client(settings) as client:
            response = await client.get(url)
        elapsed = int((time.monotonic() - started) * 1000)
        return UrlTestResult(
            status_code=response.status_code,
            elapsed_ms=elapsed,
            body_snippet=response.text[:BODY_SNIPPET_CHARS],
        )
    except Exception as exc:
        return UrlTestResult(
            elapsed_ms=int((time.monotonic() - started) * 1000), error=str(exc)
        )
